#!/usr/bin/env python3
"""Generates every app icon from app/icones/icones.json (standard library only).

Writes, for each icon: the adaptive icon (Android 8+), its foreground drawable, a flat icon for
Android 7, its background color, one <activity-alias> in the manifest, the list in Icones.java
(used to switch icons) and the list shown in Settings (web/src/ui.js).

Usage: python3 app/icones/gerar_icones.py   (then: python3 web/build.py)
"""
import json
import re
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[2]
RES = RAIZ / 'app/src/main/res'
MANIFESTO = RAIZ / 'app/src/main/AndroidManifest.xml'
JAVA = RAIZ / 'app/src/main/java/app/debtid/Icones.java'
UI = RAIZ / 'web/src/ui.js'

# The two logos, drawn on a 256-unit grid (same geometry as docs/logo.svg).
FORMAS = {
    'A': [('tinta', 'M70,52H94A6,6 0 0 1 100,58V198A6,6 0 0 1 94,204H70A6,6 0 0 1 64,198V58A6,6 0 0 1 70,52Z'),
          ('tinta', 'M116,52A76,76 0 0 1 116,204V168A40,40 0 0 0 116,88Z'),
          ('ponto', 'M120,128A13,13 0 1 0 146,128A13,13 0 1 0 120,128Z')],
    'C': [('tinta', 'M82,76H166A52,52 0 0 1 166,180H82L38,136V120Z M66,128A14,14 0 1 0 94,128A14,14 0 1 0 66,128Z')],
}
QUADRADO = 'M28,6h52a22,22 0 0 1 22,22v52a22,22 0 0 1 -22,22h-52a22,22 0 0 1 -22,-22v-52a22,22 0 0 1 22,-22z'
COR = re.compile(r'^#[0-9A-Fa-f]{6}$')


def chave(logo, cor):
    return logo.lower() if cor == 'padrao' else f'{logo.lower()}-{cor}'


def nome_res(k):
    return 'ic_launcher' if k == 'a' else 'ic_launcher_' + k.replace('-', '_').lower()


def nome_alias(k):
    return '.Icone_' + k.replace('-', '_')


def caminhos(logo, ic, mono=False):
    linhas = []
    for parte, d in FORMAS[logo]:
        cor = '#FFFFFF' if mono else ic.get(parte, ic['tinta'])
        tipo = ' android:fillType="evenOdd"' if logo == 'C' else ''
        linhas.append(f'        <path android:fillColor="{cor}"{tipo} android:pathData="{d}" />')
    return '\n'.join(linhas)


def vetor(conteudo, escala, desloc, comentario, fundo=None):
    tam = 48 if fundo else 108
    bg = f'    <path android:fillColor="{fundo}" android:pathData="{QUADRADO}" />\n' if fundo else ''
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/icones/gerar_icones.py: {comentario} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{tam}dp" android:height="{tam}dp"
    android:viewportWidth="108" android:viewportHeight="108">
{bg}    <group android:translateX="{desloc}" android:translateY="{desloc}" android:scaleX="{escala}" android:scaleY="{escala}">
{conteudo}
    </group>
</vector>
'''


def trocar_bloco(texto, inicio, fim, novo):
    i, j = texto.index(inicio), texto.index(fim)
    return texto[:i + len(inicio)] + novo + texto[j:]


def main():
    dados = json.loads((Path(__file__).parent / 'icones.json').read_text(encoding='utf-8'))
    icones = []
    for logo in ('A', 'C'):
        for ic in dados[logo]:
            for campo in ('fundo', 'tinta') + (('ponto',) if logo == 'A' else ()):
                if not COR.match(ic.get(campo, '')):
                    raise SystemExit(f'{logo} {ic.get("cor")}: cor inválida em "{campo}"')
            icones.append((logo, chave(logo, ic['cor']), ic))
    if len({k for _, k, _ in icones}) != len(icones):
        raise SystemExit('cores repetidas no mesmo logo')

    # remove what an earlier run generated
    for p in list((RES / 'drawable').glob('icone_*_frente.xml')) + list((RES / 'mipmap').glob('ic_launcher_*.xml')) + \
            list((RES / 'mipmap-anydpi-v26').glob('ic_launcher_*.xml')):
        p.unlink()

    cores = []
    for logo, k, ic in icones:
        res = nome_res(k)
        frente = 'ic_launcher_foreground' if k == 'a' else 'icone_' + k.replace('-', '_').lower() + '_frente'
        corfundo = 'icon_background' if k == 'a' else 'icone_' + k.replace('-', '_').lower() + '_fundo'
        mono = 'ic_launcher_monochrome' if logo == 'A' else 'icone_c_mono'
        desc = f'logo {logo}, {ic["cor"]}'
        if k != 'a':
            cores.append(f'    <color name="{corfundo}">{ic["fundo"].upper()}</color>\n')
        (RES / f'drawable/{frente}.xml').write_text(vetor(caminhos(logo, ic), 0.33, 11.76, desc + ' (adaptive icon foreground)'), encoding='utf-8')
        (RES / f'mipmap-anydpi-v26/{res}.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/icones/gerar_icones.py: {desc} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/{corfundo}" />
    <foreground android:drawable="@drawable/{frente}" />
    <monochrome android:drawable="@drawable/{mono}" />
</adaptive-icon>
''', encoding='utf-8')
        (RES / f'mipmap/{res}.xml').write_text(vetor(caminhos(logo, ic), 0.42, 0.24, desc + ' (Android 7, no adaptive icons)', fundo=ic['fundo']), encoding='utf-8')

    # single-color versions (Android 13+ themed icons; A is also the notification icon)
    for logo, nome in (('A', 'ic_launcher_monochrome'), ('C', 'icone_c_mono')):
        (RES / f'drawable/{nome}.xml').write_text(vetor(caminhos(logo, {}, mono=True), 0.33, 11.76, f'logo {logo}, single color'), encoding='utf-8')

    # background colors
    p = RES / 'values/colors.xml'
    padrao = next(ic for logo, k, ic in icones if k == 'a')
    texto = re.sub(r'<color name="icon_background">#[0-9A-Fa-f]{6}</color>', f'<color name="icon_background">{padrao["fundo"].upper()}</color>', p.read_text(encoding='utf-8'))
    p.write_text(trocar_bloco(texto, '    <!-- icones:inicio -->\n', '    <!-- icones:fim -->', ''.join(cores)), encoding='utf-8')

    # one launcher entry per icon; only the default is enabled
    aliases = ''.join(f'''        <activity-alias
            android:name="{nome_alias(k)}"
            android:targetActivity=".MainActivity"
            android:icon="@mipmap/{nome_res(k)}"
            android:roundIcon="@mipmap/{nome_res(k)}"
            android:enabled="{'true' if k == 'a' else 'false'}"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>
''' for _, k, _ in icones)
    MANIFESTO.write_text(trocar_bloco(MANIFESTO.read_text(encoding='utf-8'), '        <!-- icones:inicio -->\n', '        <!-- icones:fim -->', aliases), encoding='utf-8')

    # the list the app uses to switch icons
    linhas = ',\n'.join(f'            {{"{k}", "{nome_alias(k)}"}}' for _, k, _ in icones)
    JAVA.write_text(f'''package app.debtid;

/** Generated by app/icones/gerar_icones.py from app/icones/icones.json: do not edit by hand. */
final class Icones {{
    /** key used by the page → launcher entry (activity-alias) in the manifest; the first one is the default */
    static final String[][] LISTA = {{
{linhas}
    }};

    private Icones() {{}}
}}
''', encoding='utf-8')

    # the list shown in Settings
    itens = []
    for logo, k, ic in icones:
        extra = f", ponto: '{ic['ponto']}'" if logo == 'A' else ''
        itens.append(f"    {{ k: '{k}', forma: '{logo}', cor: '{ic['cor']}', fundo: '{ic['fundo']}', tinta: '{ic['tinta']}'{extra} }}")
    js = '\n  const ICONES = [\n' + ',\n'.join(itens) + '\n  ];\n  '
    UI.write_text(trocar_bloco(UI.read_text(encoding='utf-8'), '/*<icones>*/', '/*</icones>*/', js), encoding='utf-8')
    print(f'{len(icones)} ícones gerados')


if __name__ == '__main__':
    main()
